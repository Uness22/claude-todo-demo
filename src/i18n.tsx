export function tr(key: keyof typeof strings | string, lang: Lang): string {
  const entry = strings[key as string]
  if (!entry) return key as string
  if (lang === 'ar') return entry[1]
  return entry[0] // en + bi show English primary
}

export function trPair(key: keyof typeof strings | string): [string, string] {
  return strings[key as string] ?? [key as string, key as string]
}

/** Bilingual block: English line + Arabic line (when different) */
export function Bi({ k, lang }: { k: string; lang: Lang }): ReactNode {
  const [en, ar] = trPair(k)
  if (lang === 'ar') return <>{ar}</>
  if (lang === 'bi') {
    return (
      <span className="bi">
        <span className="bi-en">{en}</span>
        <span className="bi-ar" dir="rtl" lang="ar">
          {ar}
        </span>
      </span>
    )
  }
  return <>{en}</>
}

export function detectLang(text: string): 'en' | 'ar' | 'mixed' {
  const ar = (text.match(/[\u0600-\u06FF]/g) || []).length
  const en = (text.match(/[A-Za-z]/g) || []).length
  if (ar > 10 && en > 10) return 'mixed'
  if (ar > en) return 'ar'
  return 'en'
}
